#!/usr/bin/env node
// Regenerates src/sds-paths.ts from a Mafia II (Classic) install:
//
//   node src/generate-sds-paths.mjs "<Steam library>/steamapps/common/Mafia II"
//
// Maps each vanilla .sds file name (lower case) to the folder it lives in, relative to the game
// root, so the bare-sds installer can place mods that ship a lone `tables.sds` without folders.
//
// - Language folders (`sds_<lang>`) are skipped: the main game ships only the language it was
//   installed in (`pc/sds_ru` on a Russian install), so those paths differ between users.
// - A name found in several places maps to the main game's `pc/sds/...` copy when there is exactly
//   one; otherwise it's ambiguous and left out (the installer then refuses the file).
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const gameRoot = process.argv[2];
if (!gameRoot) {
  console.error('usage: node generate-sds-paths.mjs <Mafia II install folder>');
  process.exit(2);
}

const isLanguageFolder = dir => dir.split('/').some(seg => /^sds_[a-z]+$/i.test(seg));

const locations = new Map();
const walk = dir => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full);
    } else if (entry.name.toLowerCase().endsWith('.sds')) {
      const folder = relative(gameRoot, dir).split(sep).join('/');
      if (isLanguageFolder(folder)) continue;
      const name = entry.name.toLowerCase();
      if (!locations.has(name)) locations.set(name, []);
      locations.get(name).push(folder);
    }
  }
};
walk(join(gameRoot, 'pc'));

const table = {};
const ambiguous = [];
for (const [name, folders] of [...locations].sort(([a], [b]) => a.localeCompare(b))) {
  const unique = [...new Set(folders)];
  const main = unique.filter(f => f.toLowerCase().startsWith('pc/sds/'));
  if (unique.length === 1) table[name] = unique[0];
  else if (main.length === 1) table[name] = main[0];
  else ambiguous.push(name);
}

const out = join(dirname(fileURLToPath(import.meta.url)), 'sds-paths.ts');
writeFileSync(out, [
  '// AUTO-GENERATED by generate-sds-paths.mjs from a Steam install of Mafia II (Classic).',
  '// Vanilla .sds file name (lower case) -> folder relative to the game root.',
  `// ${Object.keys(table).length} names; ${ambiguous.length} ambiguous names left out: ${ambiguous.slice(0, 8).join(', ')}${ambiguous.length > 8 ? ', ...' : ''}`,
  'export const SDS_PATHS: Readonly<Record<string, string>> = {',
  ...Object.entries(table).map(([name, folder]) => `  ${JSON.stringify(name)}: ${JSON.stringify(folder)},`),
  '};',
  '',
].join('\n'));
console.log(`${out}: ${Object.keys(table).length} names, ${ambiguous.length} ambiguous`);
